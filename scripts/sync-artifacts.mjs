// Copies the Fe build output (fe/out) into the web app as one typed module.
// Run after `fe build --emit bytecode,abi` in fe/.
import { readFileSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'fe', 'out')
const read = (name) => readFileSync(join(out, name), 'utf8').trim()

let feVersion = 'unknown'
try {
  feVersion = execFileSync(process.env.FE ?? 'fe', ['--version'], { encoding: 'utf8' }).trim()
} catch {
  // fe not on PATH; the version line is informational only.
}

const body = `// Generated by scripts/sync-artifacts.mjs from fe/out. Do not edit.
// Compiler: ${feVersion}

export const feVersion = ${JSON.stringify(feVersion)}

export const vaultAbi = ${read('Vault.abi.json')} as const

export const vaultBytecode = '0x${read('Vault.bin')}' as const

export const tokenAbi = ${read('TestDollar.abi.json')} as const

export const tokenBytecode = '0x${read('TestDollar.bin')}' as const
`

const target = join(root, 'web', 'src', 'lib', 'hardstop', 'artifacts.ts')
writeFileSync(target, body)
console.log(`wrote ${target} (${body.length} bytes, ${feVersion})`)
